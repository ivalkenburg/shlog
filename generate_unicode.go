//go:build ignore

package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"
	"unicode"
)

func main() {
	client := &http.Client{Timeout: 30 * time.Second}
	fetch := func(url string) []byte {
		response, err := client.Get(url)
		if err != nil {
			panic(err)
		}
		defer response.Body.Close()
		if response.StatusCode != http.StatusOK {
			panic(response.Status)
		}
		data, err := io.ReadAll(response.Body)
		if err != nil {
			panic(err)
		}
		return data
	}
	base := "https://www.unicode.org/Public/" + unicode.Version + "/ucd/"
	widths := fetch(base + "EastAsianWidth.txt")
	emoji := fetch(base + "emoji/emoji-data.txt")
	license := fetch("https://www.unicode.org/license.txt")
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by go generate; DO NOT EDIT.\n// Unicode %s data; see UNICODE-LICENSE.\n// Sources: %sEastAsianWidth.txt and %semoji/emoji-data.txt\n\n", unicode.Version, base, base)
	out.WriteString("//go:generate go run generate_unicode.go\n\npackage main\n\n")
	for _, table := range []struct {
		name       string
		data       []byte
		properties string
	}{
		{"wideRunes", widths, "W F"},
		{"pictographicRunes", emoji, "Extended_Pictographic"},
		{"modifierBaseRunes", emoji, "Emoji_Modifier_Base"},
	} {
		var ranges [][2]uint64
		scanner := bufio.NewScanner(bytes.NewReader(table.data))
		for scanner.Scan() {
			line, _, _ := strings.Cut(scanner.Text(), "#")
			bounds, property, found := strings.Cut(line, ";")
			if !found || !strings.Contains(" "+table.properties+" ", " "+strings.TrimSpace(property)+" ") {
				continue
			}
			first, last, ranged := strings.Cut(strings.TrimSpace(bounds), "..")
			if !ranged {
				last = first
			}
			lo, err1 := strconv.ParseUint(first, 16, 32)
			hi, err2 := strconv.ParseUint(last, 16, 32)
			if err1 != nil || err2 != nil {
				panic("invalid Unicode range: " + bounds)
			}
			ranges = append(ranges, [2]uint64{lo, hi})
		}
		if err := scanner.Err(); err != nil {
			panic(err)
		}
		sort.Slice(ranges, func(i, j int) bool { return ranges[i][0] < ranges[j][0] })
		var merged [][2]uint64
		for _, r := range ranges {
			if len(merged) > 0 && r[0] <= merged[len(merged)-1][1]+1 {
				merged[len(merged)-1][1] = max(merged[len(merged)-1][1], r[1])
			} else {
				merged = append(merged, r)
			}
		}
		fmt.Fprintf(&out, "var %s = [][2]rune{\n", table.name)
		for _, r := range merged {
			fmt.Fprintf(&out, "{0x%X, 0x%X},\n", r[0], r[1])
		}
		out.WriteString("}\n\n")
	}
	source, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("unicode_tables.go", source, 0644); err != nil {
		panic(err)
	}
	if err := os.WriteFile("UNICODE-LICENSE", license, 0644); err != nil {
		panic(err)
	}
}
